package class7;

public class Operators {
    public static void main(String[] args) {
        //Addition

        int a=10;
        int b=20;
        int sum=a+b;
        System.out.println(sum);

        //Subtraction
        int num1=20;
        int num2=10;
        int sub=num1-num2;
        System.out.println(sub);

        //Multiplication
        int num3=8;
        int num4=9;
        int mul=num3*num4;
        System.out.println(mul);

        //Division
        int num5=25;
        int num6=5;
        int div=num5/num6;
        System.out.println(div);

        //Modulo
        int num7=30;
        int num8=7;
        int mod=num7%num8;
        System.out.println(mod);

    }
}